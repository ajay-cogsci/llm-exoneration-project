"""Remove contradictions between the printed GPA and the listed course grades.

The correction changes one number per affected applicant. Coursework, dates,
research, publications and the accepted CV prose are untouched, so no CV text
has to be regenerated by a model. See configs/phd_gpa_consistency_v1.json.
"""

import math
import random
import statistics
from copy import deepcopy

from phd_resumes.io import digest
from phd_resumes.rubric import evaluate

TOLERANCE = 1e-9


def check_policy(policy):
    if policy.get("version") != "phd-gpa-consistency-v1":
        raise ValueError("Unsupported GPA consistency policy")
    if type(policy["seed"]) is not int or policy["seed"] < 0:
        raise ValueError("Seed must be a nonnegative integer")
    gap = policy["max_abs_gap"]
    if type(gap) not in (int, float) or not math.isfinite(gap) or not 0 < gap <= 4:
        raise ValueError("max_abs_gap must be a positive number of grade points")
    points = policy["grade_points"]
    if not points or any(type(v) not in (int, float) or not 0 <= v <= 4 for v in points.values()):
        raise ValueError("Grade points must lie on the 4.0 scale")


def coursework_mean(facts, policy):
    return statistics.mean(policy["grade_points"][c["grade"]] for c in facts["coursework"])


def gap(facts, policy):
    return abs(facts["gpa"] - coursework_mean(facts, policy))


def is_consistent(facts, policy):
    return gap(facts, policy) <= policy["max_abs_gap"] + TOLERANCE


def candidate_gpas(row, config, sampling, policy):
    """Two-decimal GPA values that satisfy the rule, weighted by the sampler's
    own conditional bin probabilities spread uniformly inside each bin."""
    mean = coursework_mean(row["facts"], policy)
    probabilities = sampling["gpa_bin_probabilities_by_academic_level"][row["latent_academic_level"] - 1]
    values, weights = [], []
    for (low, high), probability in zip(config["gpa_bins"], probabilities):
        grid = [round(low + step / 100, 2) for step in range(int(round((high - low) * 100)) + 1)]
        for value in grid:
            if probability > 0 and abs(value - mean) <= policy["max_abs_gap"] + TOLERANCE:
                values.append(value)
                weights.append(probability / len(grid))
    return values, weights


def revise_profile(row, config, sampling, rubric, policy):
    """Return (row, change). Consistent rows are returned unchanged with None."""
    check_policy(policy)
    if is_consistent(row["facts"], policy):
        return row, None
    values, weights = candidate_gpas(row, config, sampling, policy)
    if not values:
        raise ValueError(f"No consistent GPA has sampler support for {row['profile_id']}")
    original = row["rubric"]

    def academic(value):
        facts = deepcopy(row["facts"])
        facts["gpa"] = value
        return evaluate(facts, rubric)["academic"]

    preserving = [(v, w) for v, w in zip(values, weights) if academic(v) == original["academic"]]
    preserved = bool(preserving)
    if preserved:
        values, weights = map(list, zip(*preserving))
    generator = random.Random(f"{policy['version']}:{policy['seed']}:{row['profile_id']}")
    gpa = generator.choices(values, weights)[0]
    revised = deepcopy(row)
    revised["facts"]["gpa"] = revised["features"]["gpa"] = gpa
    revised["facts_hash"] = digest(revised["facts"])
    revised["rubric"] = evaluate(revised["facts"], rubric)
    revised["strength"] = revised["rubric"]["tier"]
    change = {
        "profile_id": row["profile_id"],
        "policy_version": policy["version"],
        "coursework_grade_point_mean": round(coursework_mean(row["facts"], policy), 4),
        "original_gpa": row["facts"]["gpa"],
        "revised_gpa": gpa,
        "original_facts_hash": row["facts_hash"],
        "revised_facts_hash": revised["facts_hash"],
        "academic_rating_preserved": preserved,
        "original_tier": original["tier"],
        "revised_tier": revised["rubric"]["tier"],
        "original_selection_pattern": original["selection_pattern"],
        "revised_selection_pattern": revised["rubric"]["selection_pattern"],
    }
    # The legacy composite is a pool-relative diagnostic of the original draw.
    # It is not recomputed and must not be read as describing the revised GPA.
    revised["gpa_consistency"] = {k: change[k] for k in ("policy_version", "original_gpa", "original_facts_hash", "original_tier", "original_selection_pattern")}
    return revised, change


def revise_all(rows, config, sampling, rubric, policy):
    revised, changes = [], []
    for row in rows:
        new, change = revise_profile(row, config, sampling, rubric, policy)
        revised.append(new)
        if change:
            changes.append(change)
    if any(not is_consistent(row["facts"], policy) for row in revised):
        raise ValueError("A revised profile still violates the GPA rule")
    return revised, changes
